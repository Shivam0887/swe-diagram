/**
 * Look up a Lucide icon by its PascalCase name (e.g. "Server").
 * Returns `null` if the name isn't in the curated list.
 */
export function getLucideIcon(name: string): LucideIcon | null {
  if (!name) return null;
  const key = (name in lucideMap ? name : name.charAt(0).toUpperCase() + name.slice(1)) as LucideIconName;
  return lucideMap[key] ?? null;
}

